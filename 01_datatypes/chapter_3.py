# Integer 
english_marks = 87
science_marks = 93

total_marks = english_marks + science_marks
print(f"Total Marks is: {total_marks}")

# true division / - always returns a floating-point number
number_one = 7
number_two = 4

divide = number_one / number_two
print(f"divide of number_one by number_two: {divide}")

# floor division // - returns an integer
total_tea_bags = 7
pots = 4

bags_per_pot = total_tea_bags // pots
print(f"tea bugs per pot: {bags_per_pot}")


# modulo % 
total_cadamom_pots = 10
pots_per_cups = 3

left_over_pots = total_cadamom_pots % pots_per_cups
print(f"Remaining pots: {left_over_pots}")


# exponential ** 
base_flavour_strength = 2
scale_factor = 3

powerful_flavour = base_flavour_strength ** scale_factor
print(f"Scaled flavour strength: {powerful_flavour}")


# big numbers
large_number = 1_000_000_000 
print(f"large number: {large_number}")
